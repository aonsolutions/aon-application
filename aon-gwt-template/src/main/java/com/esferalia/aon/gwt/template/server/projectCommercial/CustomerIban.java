package com.esferalia.aon.gwt.template.server.projectCommercial;

public class CustomerIban {

	String cif;
	String iban;
	String document;
	String name;

	public String getCif() {
		return cif;
	}
	public CustomerIban setCif(String cif) {
		this.cif = cif;
		return this;
	}
	public String getIban() {
		return iban;
	}
	public CustomerIban setIban(String iban) {
		this.iban = iban;
		return this;
	}
	public String getDocument() {
		return document;
	}
	public CustomerIban setDocument(String document) {
		this.document = document;
		return this;
	}
	public String getName() {
		return name;
	}
	public CustomerIban setName(String name) {
		this.name = name;
		return this;
	}
	
	
}
