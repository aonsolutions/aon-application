package com.esferalia.aon.in.payroll.tgss.idc;

public class UnknownPDFException extends Exception {

	public UnknownPDFException() {
		super();
	}

	public UnknownPDFException(String message, Throwable cause, boolean enableSuppression, boolean writableStackTrace) {
		super(message, cause, enableSuppression, writableStackTrace);
	}

	public UnknownPDFException(String message, Throwable cause) {
		super(message, cause);
	}

	public UnknownPDFException(String message) {
		super(message);
	}

	public UnknownPDFException(Throwable cause) {
		super(cause);
	}
	

}
