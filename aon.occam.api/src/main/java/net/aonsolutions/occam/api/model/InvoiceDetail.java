package net.aonsolutions.occam.api.model;

import java.io.Serializable;
import java.sql.Timestamp;
import java.util.LinkedList;
import java.util.Optional;
import java.util.stream.Stream;

import com.esferalia.aon.watson.error.AonCoreException;
import com.esferalia.aon.watson.util.AonCollectionUtils;

import net.aonsolutions.occam.api.model.type.InvoiceSource;
import net.aonsolutions.occam.api.model.type.TaxType;

public class InvoiceDetail implements Serializable, HasAudit {

	private static final long serialVersionUID = 7597157186868662372L;

	private boolean deleted;
	private boolean autoGenerated;
	
	private Integer id;
	private Integer domain;
	private Integer invoice;
	private InvestAsset investAsset;
	private Integer project;
	private short line;
	private Integer item;
	private String description;
	private double quantity;
	private double price;
	private DiscountExpression discountExpression;
	private double taxableBase;
	private double taxes;
	private boolean prepayment;

	private Seller seller;
	private Integer workplace;
	private Integer warehouse;
	
	private InvoiceSource source;
	private Integer sourceId;

	private Account expAccount;
	
	private String creationUser;
	private Timestamp creationDate;
	private String modificationUser;
	private Timestamp modificationDate;

	
	private LinkedList<InvoiceTax> invoiceTaxes;
	
	public boolean isDeleted() {
		return deleted;
	}
	public boolean isNotDeleted() {
		return !deleted;
	}
	public InvoiceDetail setDeleted( boolean deleted) {
		this.deleted = deleted;
		return this;
	}
	
	public boolean isAutoGenerated() {
		return autoGenerated;
	}
	public InvoiceDetail setAutoGenerated(boolean autoGenerated) {
		this.autoGenerated = autoGenerated;
		return this;
	}

	public Integer getId() {
		return id;
	}
	public InvoiceDetail setId(Integer id) {
		this.id = id;
		return this;
	}
	
	public Integer getDomain() {
		return domain;
	}
	public InvoiceDetail setDomain(Integer domain) {
		this.domain = domain;
		return this;
	}
	
	public Integer getInvoice() {
		return invoice;
	}
	public InvoiceDetail setInvoice(Integer invoice) {
		this.invoice = invoice;
		return this;
	}
	
	public Optional<InvestAsset> getInvestAsset() {
		return Optional.ofNullable(investAsset);
	}
	
	public InvoiceDetail setInvestAsset(InvestAsset investAsset) {
		this.investAsset = investAsset;
		return this;
	}
	
	public Integer getProject() {
		return project;
	}
	public InvoiceDetail setProject(Integer project) {
		this.project = project;
		return this;
	}
	
	public short getLine() {
		return line;
	}
	public InvoiceDetail setLine(short line) {
		this.line = line;
		return this;
	}
	
	public Integer  getItem() {
		return item;
	}
	public InvoiceDetail setItem(Integer item) {
		this.item = item;
		return this;
	}
	
	public String getDescription() {
		return description;
	}
	public InvoiceDetail setDescription(String description) {
		this.description = description;
		return this;
	}

	public double getQuantity() {
		return quantity;
	}
	public InvoiceDetail setQuantity(double quantity) {
		this.quantity = quantity;
		return this;
	}
	
	public double getPrice() {
		return price;
	}
	public InvoiceDetail setPrice(double price) {
		this.price = price;
		return this;
	}
	
	public Optional<DiscountExpression> getDiscountExpression() {
		return Optional.ofNullable(discountExpression);
	}
	public InvoiceDetail setDiscountExpression(DiscountExpression discountExpression) {
		this.discountExpression = discountExpression;
		return this;
	}
	public InvoiceDetail setDiscountExpression(String discountExpression) {
		return setDiscountExpression( new DiscountExpression().setDiscountExpr(discountExpression));
	}
	
	public double getDiscount() {
		return getDiscountExpression().map(d -> d.getPercentage()).orElse(0.0);
	}
	public InvoiceDetail setDiscount(double discount) {
		return setDiscountExpression(new DiscountExpression().setDiscount(discount));
	}
	
	public double getTaxableBase() {
		return taxableBase;
	}
	public InvoiceDetail setTaxableBase(double taxableBase) {
		this.taxableBase = taxableBase;
		return this;
	}
	
	public double getTaxes() {
		return taxes;
	}
	public InvoiceDetail setTaxes(double taxes) {
		this.taxes = taxes;
		return this;
	}
	
	public boolean isPrepayment() {
		return prepayment;
	}
	public InvoiceDetail setPrepayment(boolean prepayment) {
		this.prepayment = prepayment;
		return this;
	}
	
	public Optional<Seller> getSeller() {
		return Optional.ofNullable(seller);
	}
	public InvoiceDetail setSeller(Seller seller) {
		this.seller = seller;
		return this;
	}
	
	public Integer getWorkplace() {
		return workplace;
	}
	public InvoiceDetail setWorkplace(Integer workplace) {
		this.workplace = workplace;
		return this;
	}

	public Integer getWarehouse() {
		return warehouse;
	}
	public InvoiceDetail setWarehouse(Integer warehouse) {
		this.warehouse = warehouse;
		return this;
	}
	
	public InvoiceSource getSource() {
		return source;
	}
	public InvoiceDetail setSource(InvoiceSource source) {
		this.source = source;
		return this;
	}
	
	public Integer getSourceId() {
		return sourceId;
	}
	public InvoiceDetail setSourceId(Integer sourceId) {
		this.sourceId = sourceId;
		return this;
	}
	
	public Optional<Account> getExpAccount() {
		return Optional.ofNullable(expAccount);
	}
	public InvoiceDetail setExpAccount(Account expAccount) {
		this.expAccount = expAccount;
		return this;
	}
	// ---------------------------------------------------------- AUDIT
	@Override
	public String getCreationUser() {
		return creationUser;
	}
	public InvoiceDetail setCreationUser(String creationUser) {
		this.creationUser = creationUser;
		return this;
	}
	@Override
	public Timestamp getCreationDate() {
		return creationDate;
	}
	public InvoiceDetail setCreationDate(Timestamp creationDate) {
		this.creationDate = creationDate;
		return this;
	}
	@Override
	public String getModificationUser() {
		return modificationUser;
	}
	public InvoiceDetail setModificationUser(String modificationUser) {
		this.modificationUser = modificationUser;
		return this;
	}
	@Override
	public Timestamp getModificationDate() {
		return modificationDate;
	}
	public InvoiceDetail setModificationDate(Timestamp modificationDate) {
		this.modificationDate = modificationDate;
		return this;
	}
	
	public boolean isAccountSource() {
		return this.getSource() == InvoiceSource.ACCOUNT;
	}
	
	public Stream<InvoiceTax> getDeletedInvoiceTaxes() {
		return AonCollectionUtils.stream(invoiceTaxes)
			.filter(InvoiceTax::isDeleted);
	}
	public Stream<InvoiceTax> taxStream() {
		return AonCollectionUtils.stream(invoiceTaxes)
			.filter(InvoiceTax::isNotDeleted);
	}
	
	public InvoiceDetail addTax(Invoice invoice, InvoiceTax invoiceTax) {
		// Chequear que solo haya uno!
		if (invoiceTaxes == null) invoiceTaxes = new LinkedList<>();
		invoiceTaxes.add(invoiceTax);
		return this;
	}
	
	// ----------------------------------------------- [VAT]
	public Optional<InvoiceTax> getVatTax() {
		return taxStream()
			.filter(it -> it.isVatType())
			.findFirst();
	}
	public InvoiceTax enableVatTax(Invoice invoice ) {
		return getVatTax().orElseGet( () -> {
			InvoiceTax it = new InvoiceTax()
				.setDomain(this.domain)
				.setInvoiceDetail(this.id)
				.setTaxType(TaxType.VAT)
				.setDeductiblePercent( getInvestAsset().map( ia -> ia.getVatPercent() ).orElse(0.0));
			addTax(invoice, it);
			return it;
		});
	}
	public InvoiceDetail disableVat(Invoice invoice) {
		return deleteTax(invoice, TaxType.VAT ); 
	}
	
	// ---------------------------------------- [WITHHOLDING]
	public Optional<InvoiceTax> getWithholding() {
		return taxStream()
			.filter(it -> it.isWithholdingType())
			.findFirst();
	}
	public InvoiceTax enableWithholding( Invoice inv ) {
		InvoiceWithholding iw = inv.getWithholding()
			.orElseThrow(() -> new AonCoreException("Activar aplicar retención en la factura") );
		return getWithholding().orElseGet( () -> {
			InvoiceTax it = new InvoiceTax()
				.setDomain(this.domain)
				.setInvoiceDetail(this.id)
				.setTaxType(TaxType.RETENTION)
				.setDirectTaxPercent(getInvestAsset().map( ia -> ia.getRetentionPercent() ).orElse(0.0))
			;
			addTax(inv, it);
			return it;
			})
			.setPercentage(iw.getPercentage())
			.setWithholdingAccount(iw.getAccount().orElse(null))
			.setWithholdingType(iw.getWithholdingType());
	}
	
	public InvoiceDetail disableWithholding( Invoice invoice ) {
		return deleteTax(invoice, TaxType.RETENTION ); 
	}
	
	
	
	private InvoiceDetail deleteTax(Invoice invoice, TaxType type) {
		taxStream()
			.filter(it -> it.getTaxType() == type)
			.forEach(it -> it.setDeleted(true));
		invoice.refreshTaxBreakdown();
		return this;
	}
	
	public boolean isTaxEnabled(Invoice invoice) {
		return (invoice != null
			 && !invoice.isUndeductible() 
			 && !this.isPrepayment());
	}
	
}
