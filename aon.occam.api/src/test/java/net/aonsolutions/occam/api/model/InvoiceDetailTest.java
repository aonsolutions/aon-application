	@Test
	void testInvoiceDetailMetadataVisitor() {
		InvoiceDetailMetadataVisitor<InvoiceDetailMetadata> v = new InvoiceDetailMetadataVisitor<>() {
			@Override public InvoiceDetailMetadata visitId() {return InvoiceDetailMetadata.ID;}
			@Override public InvoiceDetailMetadata visitDomain() {return InvoiceDetailMetadata.DOMAIN;}
			@Override public InvoiceDetailMetadata visitInvoice() {return InvoiceDetailMetadata.INVOICE;}
			@Override public InvoiceDetailMetadata visitInvestAsset() {return InvoiceDetailMetadata.INVEST_ASSET;}
			@Override public InvoiceDetailMetadata visitProject() {return InvoiceDetailMetadata.PROJECT;}
			@Override public InvoiceDetailMetadata visitLine() {return InvoiceDetailMetadata.LINE;}
			@Override public InvoiceDetailMetadata visitItem() {return InvoiceDetailMetadata.ITEM;}
			@Override public InvoiceDetailMetadata visitDescription() {return InvoiceDetailMetadata.DESCRIPTION;}
			@Override public InvoiceDetailMetadata visitQuantity() {return InvoiceDetailMetadata.QUANTITY;}
			@Override public InvoiceDetailMetadata visitPrice() {return InvoiceDetailMetadata.PRICE;}
			@Override public InvoiceDetailMetadata visitDiscountExpr() {return InvoiceDetailMetadata.DISCOUNT_EXPR;}
			@Override public InvoiceDetailMetadata visitSource() {return InvoiceDetailMetadata.SOURCE;}
			@Override public InvoiceDetailMetadata visitSourceId() {return InvoiceDetailMetadata.SOURCE_ID;}
			@Override public InvoiceDetailMetadata visitTaxableBase() {return InvoiceDetailMetadata.TAXABLE_BASE;}
			@Override public InvoiceDetailMetadata visitTaxes() {return InvoiceDetailMetadata.TAXES;}
			@Override public InvoiceDetailMetadata visitPrepayment() {return InvoiceDetailMetadata.PREPAYMENT;}
			@Override public InvoiceDetailMetadata visitSeller() {return InvoiceDetailMetadata.SELLER;}
			@Override public InvoiceDetailMetadata visitWorkplace() {return InvoiceDetailMetadata.WORKPLACE;}
			@Override public InvoiceDetailMetadata visitWarehouse() {return InvoiceDetailMetadata.WAREHOUSE;}
			@Override public InvoiceDetailMetadata visitInvoiceTaxes() {return InvoiceDetailMetadata.INVOICE_TAXES;}
			@Override public InvoiceDetailMetadata visitExpAccount() {return InvoiceDetailMetadata.EXP_ACCOUNT;}
		};
		AonCollectionUtils.stream(InvoiceDetailMetadata.values())
			.forEach(a -> assertSame(a, a.visit(v)));
	}
	
