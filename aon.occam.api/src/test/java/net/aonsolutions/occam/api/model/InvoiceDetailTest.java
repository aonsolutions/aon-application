package net.aonsolutions.occam.api.model;

import org.junit.jupiter.api.Test;

class InvoiceDetailTest {
	
	@Test
	void testInvoiceDetail() {
		InvoiceDetail expected = AonMocker.mock(InvoiceDetail.class);
		InvoiceDetail actual = new InvoiceDetail()
			.setDeleted(expected.isDeleted())
			.setAutoGenerated(expected.isAutoGenerated())
			.setId(expected.getId())
			.setDomain(expected.getDomain())
			.setInvoice(expected.getInvoice())
			.setInvestAsset(expected.getInvestAsset().orElse(null))
			.setProject(expected.getProject())
			.setLine(expected.getLine())
			.setItem(expected.getItem())
			.setDescription(expected.getDescription())
			.setQuantity(expected.getQuantity())
			.setPrice(expected.getPrice())
			.setDiscountExpression(expected.getDiscountExpression().orElse(null))
			.setTaxableBase(expected.getTaxableBase())
			.setTaxes(expected.getTaxes())
			.setPrepayment(expected.isPrepayment())
			.setSeller(expected.getSeller().orElse(null))
			.setWorkplace(expected.getWorkplace())
			.setWarehouse(expected.getWarehouse())
			.setSource(expected.getSource())
			.setSourceId(expected.getSourceId())
			.setExpAccount(expected.getExpAccount().orElse(null))
			.setCreationUser(expected.getCreationUser())
			.setCreationDate(expected.getCreationDate())
			.setModificationUser(expected.getModificationUser())
			.setModificationDate(expected.getModificationDate())
		;
		AonAsserts.assertClassEquals(expected, actual);
	}
}
