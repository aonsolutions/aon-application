	public List<InvoiceTax> getInvoiceTaxes() {
		if(invoiceTaxes == null) {
			invoiceTaxes = new LinkedList<>();
		}
		return invoiceTaxes;
	}
	public InvoiceDetail setInvoiceTaxes(List<InvoiceTax> invoiceTaxes) {
		this.invoiceTaxes = invoiceTaxes;
		return this;
	}
	private InvoiceDetail addInvoiceTax(Invoice invoice, InvoiceTax invoiceTax) {
		invoice.getTaxBreakdown()
			.ifPresent(tb -> tb.add(invoiceTax));
		;
		getInvoiceTaxes().add(invoiceTax);
		return this;
	}
	
	// ----------------------------------------------- [VAT]
	public Optional<InvoiceTax> getVatTax() {
		return getInvoiceTaxes()
			.stream()
			.filter(it -> it.isVatType())
			.findFirst();
	}
	public InvoiceTax ensureVatTax(Invoice invoice) {
		return getVatTax().orElseGet(() -> addVatTax(invoice).getVatTax().orElse(null) );
	}
	private InvoiceDetail addVatTax(Invoice invoice ) {
		return addInvoiceTax(invoice, new InvoiceTax()
			.setDomain(this.domain)
			.setInvoiceDetail(this.id)
			.setTaxType(TaxType.VAT)
		);
	}
	public InvoiceDetail deleteVatTax() {
		return deleteTax( TaxType.VAT ); 
	}
	
	// -------------------------------------- [WITHHOLDING]

	public Optional<InvoiceTax> getWithholdingTax() {
		return getInvoiceTaxes()
			.stream()
			.filter(it -> it.isWithholdingType())
			.findFirst();
	}
	public InvoiceTax ensureWithholdingTax(Invoice inv) {
		return getWithholdingTax()
			.orElseGet(() -> addWithholdingTax(inv).getWithholdingTax().orElse( null ) ); 
	}
	public InvoiceDetail addWithholdingTax( Invoice inv ) {
		InvoiceWithholding wd = inv.getWithholding()
			.orElseGet( inv::ensureWithholdingData );
		return addInvoiceTax( inv, new InvoiceTax()
			.setDomain(this.domain)
			.setInvoiceDetail(this.id)
			.setTaxType(TaxType.RETENTION)
			.setWithholdingType( wd.getWithholdingType() )
			.setPercentage( wd.getPercentage() )
		);
	}
	public InvoiceDetail deleteWithholdingTax() {
		return deleteTax( TaxType.RETENTION ); 
	}

	private InvoiceDetail deleteTax(TaxType type) {
		return setInvoiceTaxes(
			getInvoiceTaxes()
				.stream()
				.filter(it -> it.getTaxType() != type)
				.collect(Collectors.toCollection(LinkedList::new) )
		);
	
	}
	
