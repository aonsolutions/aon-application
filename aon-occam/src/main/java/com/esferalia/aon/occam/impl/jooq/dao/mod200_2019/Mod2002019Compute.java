	// Calculo del desglose de determinadas casillas que contienen 3 o mas columnas
	// Los calculos se realizan siempre sobre las 3 columnas de la derecha que son 
	// del tipo "Deducción pendiente/generada", "Aplicado en esta liquidación", "Pendiente de aplicacion en periodos futuros"
	// breakdown: Enumerado con las casillas del desglose
	// breakdownKey : Casilla del desglose (casilla central, de las 3 columnas derechas de la fila de los totales)
	// noKeys : Array de casillas izquierdas (de las 3 columnas derechas) de otras filas que no debe acumularse en los totales, ni calcular la diferencia
	// Todas las casillas de desglose estan en Mod2002019Key, no hay ninguna actualmente en Mod2002019KeyDC
	private static void AddBreakdown(IMod200KeysProvider[] breakdown, Mod2002019Key breakdownKey, Mod2002019Key[] noKeys) {
		
		String s1 = "";
		String s2 = "";
		String s3 = "";
		
		for (IMod200KeysProvider k: breakdown) {
			
			Mod2002019Key key1 = (Mod2002019Key) k.getKeys()[k.getKeys().length-3];
			Mod2002019Key key2 = (Mod2002019Key) k.getKeys()[k.getKeys().length-2];
			Mod2002019Key key3 = (Mod2002019Key) k.getKeys()[k.getKeys().length-1];
			
			// Primera casilla de las filas que no deben acumularse
			if (key1 != null && noKeys != null && Arrays.asList(noKeys).contains(key1))
				continue;
			
			if (key2 == breakdownKey) {
				// Fila que lleva los totales
				COMPUTE_EXPRESSION_MAP.put(key1, s1);
				COMPUTE_EXPRESSION_MAP.put(key2, s2);
				COMPUTE_EXPRESSION_MAP.put(key3, s3);				
			}
			else { // Resto de casillas, se acumulan para los totales, y se genera la operacion para la diferencia (si procede)	
				
				// Sumatorio primera columna
				if (key1 != null) {
					// Si es el desglose la casilla 561 (compensacion de cuotas cooperativas), 
					// esta casilla es cero si no es cooperativa
//					if (breakdownKey == Mod2002019Key.LQ561)
//						COMPUTE_EXPRESSION_MAP.put(key1,"(!isCooperativa())?(0.0):("+key1.toString()+")");

					s1 = s1 + (s1.isEmpty() ? "" : "+") + key1.toString();
				}
				
				// Sumatorio segunda columna
				if (key2 != null) {
					// Si es el desglose la casilla 561 (compensacion de cuotas cooperativas), 
					// esta casilla es cero si no es cooperativa
//					if (breakdownKey == Mod2002019Key.LQ561)
//						COMPUTE_EXPRESSION_MAP.put(key2,"(!isCooperativa())?(0.0):("+key2.toString()+")");
					
					s2 = s2 + (s2.isEmpty() ? "" : "+") + key2.toString();
				}
				
				// Sumatorio tercera columna y Diferencia (importe_pendiente - importe_aplicado)
				if (key3 != null) {
					s3 = s3 + (s3.isEmpty() ? "" : "+") + key3.toString();
					COMPUTE_EXPRESSION_MAP.put(key3 , key1.toString() + "-" + key2.toString());					
				}				
			}
		}		
	}
	
	private static void AddBreakdown(IMod200KeysProvider[] breakdown, Mod2002019Key breakdownKey) {
		AddBreakdown(breakdown, breakdownKey, null);	
	}
	
