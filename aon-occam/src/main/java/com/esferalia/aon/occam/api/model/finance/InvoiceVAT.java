package com.esferalia.aon.occam.api.model.finance;

import java.io.Serializable;
import java.util.Optional;

import com.esferalia.aon.occam.api.model.Account;
import com.esferalia.aon.occam.api.model.type.InvoiceSource;
import com.esferalia.aon.occam.api.model.type.VatDeductionType;
import com.esferalia.aon.watson.util.AonCollectionUtils;
import com.esferalia.aon.watson.util.AonMathUtils;

public class InvoiceVAT implements Serializable {

	private static final long serialVersionUID = 8897444490096530091L;

	private InvoiceDetail invoiceDetail;
	private Integer invoiceTaxId;
	private Integer invoiceDetailId;
	private boolean autoGenerated;
	
	private boolean quotaEdited;
	private boolean surchargeQuotaEdited;
	private boolean deductibleQuotaEdited;
	
	private VatDeductionType vatDeductionType;
	private double base;
	private double percentage;
	private double quota;
	private double surcharge;
	private double surchargeQuota;
	private Integer investAsset;
	private double deductiblePercent;
	private double deductibleQuota;
	private double directTaxPercent;
	private boolean withholding;
	private boolean prepayment;
	
	private Account outputAccount;
	private Account inputAccount;
	private Account adjAccount;
	private Account adjDirectTaxAccount;
	private Account expAccount;
	
	public Integer getInvoiceTaxId() {
		return invoiceTaxId;
	}
	public InvoiceVAT setInvoiceTaxId(Integer invoiceTaxId) {
		this.invoiceTaxId = invoiceTaxId;
		return this;
	}
	public Integer getInvoiceDetailId() {
		return invoiceDetailId;
	}
	public InvoiceVAT setInvoiceDetailId(Integer invoiceDetailId) {
		this.invoiceDetailId = invoiceDetailId;
		return this;
	}
	public boolean isAutoGenerated() {
		return autoGenerated;
	}
	public InvoiceVAT setAutoGenerated(boolean autoGenerated) {
		this.autoGenerated = autoGenerated;
		return this;
	}
	public boolean isAnyQuotaEdited() {
		return isQuotaEdited() 
			|| isSurchargeQuotaEdited() 
			|| isDeductibleQuotaEdited();
	}
	public boolean isQuotaEdited() {
		return quotaEdited;
	}
	public InvoiceVAT setQuotaEdited(boolean quotaEdited) {
		this.quotaEdited = quotaEdited;
		return this;
	}
	public boolean isSurchargeQuotaEdited() {
		return surchargeQuotaEdited;
	}
	public InvoiceVAT setSurchargeQuotaEdited(boolean surchargeQuotaEdited) {
		this.surchargeQuotaEdited = surchargeQuotaEdited;
		return this;
	}
	public boolean isDeductibleQuotaEdited() {
		return deductibleQuotaEdited;
	}
	public InvoiceVAT setDeductibleQuotaEdited(boolean deductibleQuotaEdited) {
		this.deductibleQuotaEdited = deductibleQuotaEdited;
		return this;
	}
	
	public VatDeductionType getVatDeductionType() {
		return vatDeductionType;
	}

	public InvoiceVAT setVatDeductionType(VatDeductionType vatDeductionType) {
		this.vatDeductionType = vatDeductionType;
		return this;
	}

	public double getBase() {
		return base;
	}

	public InvoiceVAT setBase(double base) {
		this.base = base;
		return this;
	}

	public double getPercentage() {
		return percentage;
	}

	public InvoiceVAT setPercentage(double percentage) {
		this.percentage = percentage;
		return this;
	}

	public double getQuota() {
		return quota;
	}

	public InvoiceVAT setQuota(double quota) {
		this.quota = quota;
		return this;
	}

	public double getSurcharge() {
		return surcharge;
	}

	public InvoiceVAT setSurcharge(double surcharge) {
		this.surcharge = surcharge;
		return this;
	}

	public double getSurchargeQuota() {
		return surchargeQuota;
	}

	public InvoiceVAT setSurchargeQuota(double surchargeQuota) {
		this.surchargeQuota = surchargeQuota;
		return this;
	}

	public double getDeductibleQuota() {
		return deductibleQuota;
	}

	public double getNoDeductibleQuota() {
		return AonMathUtils.round( getQuota() - getDeductibleQuota() );
	}

	public InvoiceVAT setDeductibleQuota(double deductibleQuota) {
		this.deductibleQuota = deductibleQuota;
		return this;
	}
	
	public double getDirectTaxPercent() {
		return directTaxPercent;
	}
	public InvoiceVAT setDirectTaxPercent(double directTaxPercent) {
		this.directTaxPercent = directTaxPercent;
		return this;
	}
	
	public double getDirectTaxNoDedExpenses() {
		double percent = AonMathUtils.round(100 - this.directTaxPercent);
		return AonMathUtils.round( this.base *  percent / 100);		
	}
	public double getDirectTaxDedExpenses() {
		return AonMathUtils.round( getBase() - getDirectTaxNoDedExpenses() );
	}

	public boolean isWithholding() {
		return withholding;
	}
	public InvoiceVAT setWithholding(boolean withholding) {
		this.withholding = withholding;
		return this;
	}
	public boolean isPrepayment() {
		return prepayment;
	}
	public InvoiceVAT setPrepayment(boolean prepayment) {
		this.prepayment = prepayment;
		return this;
	}
	
	public Integer getInvestAsset() {
		return investAsset;
	}
	
	public InvoiceVAT setInvestAsset(Integer investAsset) {
		this.investAsset = investAsset;
		return this;
	}
	
	public double getDeductiblePercent() {
		return deductiblePercent;
	}

	public InvoiceVAT setDeductiblePercent(double deductiblePercent) {
		this.deductiblePercent = deductiblePercent;
		return this;
	}

	public Optional<Account> getOutputAccount() {
		return Optional.ofNullable(outputAccount);
	}
	public InvoiceVAT setOutputAccount(Account outputAccount) {
		this.outputAccount = outputAccount;
		return this;
	}

	public Optional<Account> getInputAccount() {
		return Optional.ofNullable(inputAccount);
	}
	public InvoiceVAT setInputAccount(Account inputAccount) {
		this.inputAccount = inputAccount;
		return this;
	}

	public Optional<Account> getAdjAccount() {
		return Optional.ofNullable(adjAccount);
	}
	public InvoiceVAT setAdjAccount(Account adjAccount) {
		this.adjAccount = adjAccount;
		return this;
	}

	public Optional<Account> getAdjDirectTaxAccount() {
		return Optional.ofNullable(adjDirectTaxAccount);
	}
	public InvoiceVAT setAdjDirectTaxAccount(Account adjDirectTaxAccount) {
		this.adjDirectTaxAccount = adjDirectTaxAccount;
		return this;
	}

	public Optional<Account> getExpAccount() {
		return Optional.ofNullable(expAccount);
	}
	public InvoiceVAT setExpAccount(Account expAccount) {
		this.expAccount = expAccount;
		return this;
	}

	public InvoiceDetail getInvoiceDetail() {
		return invoiceDetail;
	}
	public InvoiceVAT setInvoiceDetail(InvoiceDetail invoiceDetail) {
		this.invoiceDetail = invoiceDetail;
		return this;
	}
	public boolean isInvoiceDetailPresent() {
		return this.invoiceDetail != null;
	}
	public boolean isAccountingSource() {
		return this.invoiceDetail == null
		   || this.invoiceDetail.getSource() == InvoiceSource.ACCOUNT
//		   || this.invoiceDetail.getSource() == InvoiceSource.TEDI
		   ;
	}
	
	public InvoiceVAT clone() {
		return new InvoiceVAT()
			.setInvoiceTaxId(this.invoiceTaxId)
			.setInvoiceDetailId(this.invoiceDetailId)
			.setAutoGenerated(this.autoGenerated)
			.setQuotaEdited(this.quotaEdited)
			.setSurchargeQuotaEdited(this.surchargeQuotaEdited)
			.setDeductibleQuotaEdited(this.deductibleQuotaEdited)
			.setVatDeductionType(this.vatDeductionType)
			.setBase(this.base)
			.setPercentage(this.percentage)
			.setQuota(this.quota)
			.setSurcharge(this.surcharge)
			.setSurchargeQuota(this.surchargeQuota)
			.setInvestAsset(this.investAsset)
			.setDeductiblePercent(this.deductiblePercent)
			.setDeductibleQuota(this.deductibleQuota)
			.setDirectTaxPercent(this.directTaxPercent)
			.setWithholding(this.withholding)
			.setPrepayment(this.prepayment) 
			.setOutputAccount(this.outputAccount)
			.setInputAccount(this.inputAccount)
			.setAdjAccount(this.adjAccount)
			.setAdjDirectTaxAccount(this.adjDirectTaxAccount)
			.setExpAccount(this.expAccount)
		;
	}
	
	public void syncChangesToWrappedDetail() {
		if ( this.isInvoiceDetailPresent() ) {
			// ACCOUNT
			getExpAccount().ifPresent(a -> this.getInvoiceDetail().setExpAccount(a));
			
			// INVEST ASSET
			this.getInvoiceDetail().setInvestAsset( this.getInvestAsset() );
			InvoiceTax it = AonCollectionUtils
				.stream(this.getInvoiceDetail().getInvoiceTaxes())
					.filter( i -> i.isVatType() )
					.findAny()
					.orElse(null);
			if ( it != null ) {
				it.setDeductiblePercent( this.getDeductiblePercent() );
				it.setDeductibleQuota( this.getDeductibleQuota() );
			}
		}
	}
}
