package com.esferalia.aon.occam.test.accounting.account;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertNotNull;

import java.io.IOException;
import java.util.List;

import org.junit.jupiter.api.Test;

import com.esferalia.aon.occam.api.ACCOUNTING;
import com.esferalia.aon.occam.api.model.Account;
import com.esferalia.aon.occam.api.model.Occam;
import com.esferalia.aon.occam.test.AbstractOccamTest;
import com.esferalia.aon.occam.test.faker.AccountingFaker;

public class AccountGenerateLowLevelTest extends AbstractOccamTest {
	@Test
	public void test() throws IOException {
		Account fakeAccountLvl1 = AccountingFaker.getAccount(ctx, "8");
		Account fakeAccountLvl2 = AccountingFaker.getAccount(ctx, "88");
		Account fakeAccountLvl3 = AccountingFaker.getAccount(ctx, "888");
		Account generatedLvl1 = null;
		Account generatedLvl2 = null;
		Account generatedLvl3 = null;
		
		Account lowerLevel1 = ACCOUNTING.getAccount(ctx, "8");
		if (lowerLevel1 == null) {
			generatedLvl1 = ACCOUNTING.save(DOMAIN_NAME, DOMAIN_ID, USER, fakeAccountLvl1);
		}
		Account lowerLevel2 = ACCOUNTING.getAccount(ctx, "88");
		if (lowerLevel2 == null) {
			generatedLvl2 = ACCOUNTING.save(DOMAIN_NAME, DOMAIN_ID, USER, fakeAccountLvl2);
		}
		Account lowerLevel3 = ACCOUNTING.getAccount(ctx, "888");
		if (lowerLevel3 == null) {
			generatedLvl3 = ACCOUNTING.save(DOMAIN_NAME, DOMAIN_ID, USER, fakeAccountLvl3);
		}
		
		
		ACCOUNTING.getAccounts(DOMAIN_NAME, DOMAIN_ID, USER, f -> f.getCodeProperty().between("888000000", "888099999")).forEach(acc -> ACCOUNTING.delete(DOMAIN_NAME, DOMAIN_ID, USER, acc));
		Account lowerLevel4 = ACCOUNTING.getAccount(ctx, "8880");
		if (lowerLevel4 != null) {
			ACCOUNTING.delete(DOMAIN_NAME, DOMAIN_ID, USER, lowerLevel4);
		}
		
		
		Account account = AccountingFaker.getAccount(ctx, "888000000");
		
		List<Account> autogenerated = ACCOUNTING.generateLowerLevels(new Occam().setDomain(DOMAIN_ID).setDomainName(DOMAIN_NAME).setUser(USER), account, 3);
		assertNotNull(autogenerated,"Debe haber una cuenta autogenerada de nivel 4");
		assertEquals(1, autogenerated.size(),"Debe haber una cuenta autogenerada de nivel 4");
		
		ACCOUNTING.save(DOMAIN_NAME, DOMAIN_ID, USER, account);
		
		ACCOUNTING.delete(DOMAIN_NAME, DOMAIN_ID, USER, account);
		ACCOUNTING.getAccounts(DOMAIN_NAME, DOMAIN_ID, USER, f -> f.getCodeProperty().between("888000000", "888099999")).forEach(acc -> ACCOUNTING.delete(DOMAIN_NAME, DOMAIN_ID, USER, acc));
		autogenerated.stream().sorted((ac1, ac2) -> {
			if (ac1 != null && ac2 != null) {
				return Byte.compare(ac2.getLevel(), ac1.getLevel());
			}
			return -1;
		}).forEach(acc -> ACCOUNTING.delete(DOMAIN_NAME, DOMAIN_ID, USER, acc));
		if (generatedLvl3 != null) {
			ACCOUNTING.delete(DOMAIN_NAME, DOMAIN_ID, USER, generatedLvl3);			
		}
		if (generatedLvl2 != null) {
			ACCOUNTING.delete(DOMAIN_NAME, DOMAIN_ID, USER, generatedLvl2);			
		}
		if (generatedLvl1 != null) {
			ACCOUNTING.delete(DOMAIN_NAME, DOMAIN_ID, USER, generatedLvl1);			
		}
		
	}	
}
