package com.esferalia.aon.file.pms.webpol.data;

/**
 * 
 * TIPO2 - Registro del tipo 2
 * 
 * datos del viajero
 * 
 */
public class TIPO2 {
	
	private String numeroDocumentoEsp;
	private String numeroPasaporteExtranjeros;
	private String tipoDocumento;
	private String fechaExpedicionDocumento;
	private String primerApellido;
	private String segundoApellido;
	private String nombre;
	private String sexo;
	private String fechaNacimiento;
	private String paisNacionalidad;
	private String fechaEntrada;
	
	
	public String getNumeroDocumentoEsp() {
		return numeroDocumentoEsp;
	}
	public void setNumeroDocumentoEsp(String numeroDocumentoEsp) {
		this.numeroDocumentoEsp = numeroDocumentoEsp;
	}
	public String getNumeroPasaporteExtranjeros() {
		return numeroPasaporteExtranjeros;
	}
	public void setNumeroPasaporteExtranjeros(String numeroPasaporteExtranjeros) {
		this.numeroPasaporteExtranjeros = numeroPasaporteExtranjeros;
	}
	public String getTipoDocumento() {
		return tipoDocumento;
	}
	public void setTipoDocumento(String tipoDocumento) {
		this.tipoDocumento = tipoDocumento;
	}
	public String getFechaExpedicionDocumento() {
		return fechaExpedicionDocumento;
	}
	public void setFechaExpedicionDocumento(String fechaExpedicionDocumento) {
		this.fechaExpedicionDocumento = fechaExpedicionDocumento;
	}
	public String getPrimerApellido() {
		return primerApellido;
	}
	public void setPrimerApellido(String primerApellido) {
		this.primerApellido = primerApellido;
	}
	public String getSegundoApellido() {
		return segundoApellido;
	}
	public void setSegundoApellido(String segundoApellido) {
		this.segundoApellido = segundoApellido;
	}
	public String getNombre() {
		return nombre;
	}
	public void setNombre(String nombre) {
		this.nombre = nombre;
	}
	public String getSexo() {
		return sexo;
	}
	public void setSexo(String sexo) {
		this.sexo = sexo;
	}
	public String getFechaNacimiento() {
		return fechaNacimiento;
	}
	public void setFechaNacimiento(String fechaNacimiento) {
		this.fechaNacimiento = fechaNacimiento;
	}
	public String getPaisNacionalidad() {
		return paisNacionalidad;
	}
	public void setPaisNacionalidad(String paisNacionalidad) {
		this.paisNacionalidad = paisNacionalidad;
	}
	public String getFechaEntrada() {
		return fechaEntrada;
	}
	public void setFechaEntrada(String fechaEntrada) {
		this.fechaEntrada = fechaEntrada;
	}
	
}
