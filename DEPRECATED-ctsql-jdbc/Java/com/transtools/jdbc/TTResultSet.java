	/**
	 *  getObject method gets the value of the designated column in the current row
	 *  of the ResultSet object as an Java Object.
	 *
	 * @param  columnIndex       represents the column index which resultSet gets
	 *      the value as a Java Object.
	 * @return                   the object that contains the value requiered as a
	 *      Object.
	 * @exception  SQLException  Description of Exception
	 * @jdbc.jcosmos             Necesario de implementar para JCosmos.
	 */
	public Object getObject(int columnIndex) throws SQLException {
		Object result = null;

		setWasNull(false);
		switch (cursor.getColumnType(columnIndex - 1)) {
						case CtsqlType.CHAR_TYPE:
							result = getString(columnIndex);
							break;
						case CtsqlType.SMALLINT_TYPE:
							result = new Short(getShort(columnIndex));
							break;
						case CtsqlType.INTEGER_TYPE:
						case CtsqlType.SERIAL_TYPE:
							result = new Integer(getInt(columnIndex));
							break;
						case CtsqlType.DECIMAL_TYPE:
							result = new Double(getDouble(columnIndex));
							break;
						case CtsqlType.DATE_TYPE:
							result = getDate(columnIndex);
							break;
						case CtsqlType.DATETIME_TYPE:
							result = getDateTime(columnIndex);
							break;
						case CtsqlType.BINARY_TYPE:
							result = getBytes(columnIndex);
							break;
						case CtsqlType.TIME_TYPE:
							result = getTime(columnIndex);
							break;
						case CtsqlType.MONEY_TYPE:
							result = new Double(getDouble(columnIndex));
							break;
						default:
							ExceptionManager.getManager().throwException(CtsqlException.INVALID_COLUMN_TYPE,
								CtsqlException.getMessage(CtsqlException.INVALID_COLUMN_TYPE));
		}
		return (wasNull() ? null : result);
	}


