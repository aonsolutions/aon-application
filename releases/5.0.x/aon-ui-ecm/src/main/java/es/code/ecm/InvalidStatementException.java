public class InvalidStatementException extends Exception {

	/**
	 * Constructs a <code>InvalidStatementException</code> object.
	 */
	public InvalidStatementException() {
		super();
	}

	/**
	 * Constructs a <code>InvalidStatementException</code> object.
	 * 
	 * @param cause
	 */
	public InvalidStatementException(Throwable cause) {
		super(cause);
	}

}
