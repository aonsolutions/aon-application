	private void trasEpigraph(Connection source, Connection target) throws SQLException {
		String SELECT_EPIGRAFES = "SELECT" 
	 			+ " iaemod.id_iae, listamod.epigrafe"
				+ " FROM iaemod"
				+ " INNER JOIN listamod ON  iaemod.id_iae = listamod.id_iae"; 
		String SELECT_EPIGRAFE = "SELECT" 
				+ " epigrafe,literal" 
				+ " FROM epigrafe " 
				+ " WHERE epigrafe = ? ";

		PreparedStatement insert = null;
		PreparedStatement stmt = null;
		ResultSet rs = null;
		PreparedStatement stmt1 = null;
		ResultSet rs1 = null;
		
		try {
			insert = target.prepareStatement(INSERT_TABLE_EPIGRAFE);
			stmt = source.prepareStatement(SELECT_EPIGRAFES);	
			rs = stmt.executeQuery();
			stmt1 = source.prepareStatement(SELECT_EPIGRAFE);
			int i = 0;
			while (rs.next()) {
				insert.setInt(1, i );
				insert.setInt(2, rs.getInt(1) );
				String epi = rs.getString(2);
				insert.setString(3, epi );
				String epigrafe = StringUtils.remove(epi, ".");
				if ("---".equals(epigrafe)) {
					insert.setString(4, "PRODUCCIÓN DE MEJILLÓN EN BATEA" );
				} else {
					stmt1.setInt(1, Integer.parseInt(epigrafe));	
					rs1 = stmt1.executeQuery();	
					if (rs1.next()) {
						insert.setString(4, rs1.getString(2) );
					} else {
						insert.setNull(4, Types.CHAR );	
					}
					DbUtils.closeQuietly(rs1);
				}
				insert.execute();
				i++;
			}
			System.out.println("" + i + " epígrafes insertados.");
		} finally {
			DbUtils.closeQuietly(rs);
			DbUtils.closeQuietly(stmt);
			DbUtils.closeQuietly(rs1);
			DbUtils.closeQuietly(stmt1);
			DbUtils.closeQuietly(insert);
		}
	}

