package com.code.aon.fiscal.enumeration;

public class FiscalActivityInfoKeyEntry {
	
	private int value;
	private String label;
	
	public FiscalActivityInfoKeyEntry(int value , String label) {
		this.value = value;  
		this.label = label;
	}
	
	public int getValue() {
		return value;
	}
	public String getLabel() {
		return label;
	}
	
	

}
