	public static byte[] AnsiToOem(byte[] from) {
		if(from == null)
		  return null;
		byte[] to = new byte[from.length];

		int i;
		for (i = 0; i < from.length; i++) {
			if ((from[i] & 0x80) != 0) {
				to[i] = (byte) (AnsiToOemConv[from[i] & 0x7f]);
			}else{
				to[i] = from[i];
			}
		}
		return to;
	}


