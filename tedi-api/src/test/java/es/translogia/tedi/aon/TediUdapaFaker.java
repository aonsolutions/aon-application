	private static double calculate(JSONObject invoice) {
		JSONArray details = invoice.getJSONArray(IConstants.DETAILS);
		double total = 0;
		for (int i = 0; i < details.length(); i++) {
			JSONObject detail = details.getJSONObject(i);
			double base = 0;
			double vat = 0;
			if (detail.has(IConstants.AMOUNT)) {
				base = detail.getDouble(IConstants.AMOUNT);
				total = total + base;
			}
			if (detail.has(IConstants.VAT)) {
				vat = detail.getDouble(IConstants.VAT);
				TediInvoiceTax invoiceTax = new TediInvoiceTax().setTaxType(TediTaxType.IVA).setBase(base)
						.setPercentage(vat);
				if (detail.has(IConstants.SURCHARGE)) {
					double surcharge = detail.getDouble(IConstants.SURCHARGE);
					invoiceTax.setSurcharge(surcharge);
				}
				mergeTax(invoice, invoiceTax);
			}
		}
		invoice.put(IConstants.TOTAL, round(total));

		if (invoice.has(IConstants.TAXES)) {
			total = 0;
			JSONArray taxes = invoice.getJSONArray(IConstants.TAXES);
			for (int i = 0; i < taxes.length(); i++) {
				JSONObject jsonTax = taxes.getJSONObject(i);
				double base = jsonTax.getDouble(IConstants.BASE);
				double percentage = jsonTax.getDouble(IConstants.PERCENTAGE);
				double quota = round((base * percentage) / 100);
				jsonTax.put(IConstants.QUOTA, quota);
				double sq = 0;
				if (jsonTax.has(IConstants.SURCHARGE)) {
					double surcharge = jsonTax.getDouble(IConstants.SURCHARGE);
					sq = round((base * surcharge) / 100);
					jsonTax.put(IConstants.SURCHARGE_QUOTA, sq);
				}
				total = total + base + quota + sq;
			}
		}
		invoice.put(IConstants.TOTAL, round(total));
		return round(total);
	}

	private static double round(double value) {
		return new BigDecimal(Double.toString(value)).setScale(2, RoundingMode.HALF_UP).doubleValue();
	}

	private static void mergeTax(JSONObject invoice, TediInvoiceTax tax) {
		if (!invoice.has(IConstants.TAXES)) {
			invoice.put(IConstants.TAXES, new JSONArray());
		}
		boolean found = false;
		JSONArray taxes = invoice.getJSONArray(IConstants.TAXES);
		for (int i = 0; i < taxes.length(); i++) {
			JSONObject jsonTax = taxes.getJSONObject(i);
			TediInvoiceTax tit = TediInvoiceTaxJSON.fromJSON(jsonTax);
			double p1 = tit.getPercentage() == null ? Double.MIN_VALUE : tit.getPercentage();
			double p2 = tax.getPercentage() == null ? Double.MIN_VALUE : tax.getPercentage();
			double s1 = tit.getSurcharge() == null ? Double.MIN_VALUE : tit.getSurcharge();
			double s2 = tax.getSurcharge() == null ? Double.MIN_VALUE : tax.getSurcharge();
			if (tit.getTaxType() == tax.getTaxType() && p1 == p2 && s1 == s2) {
				found = true;
				double b = round(tax.getBase() + tit.getBase());
				jsonTax.put(IConstants.BASE, b);
			}
		}
		if (!found) {
			taxes.put(TediInvoiceTaxJSON.toJSON(tax));
		}
	}
