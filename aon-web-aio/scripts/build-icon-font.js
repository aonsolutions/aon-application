// 'arrow-big-down' -> ARROW_BIG_DOWN, 'SeguridadSocial' -> SEGURIDAD_SOCIAL
function constName(icon) {
    return icon
        .replace(/([a-z0-9])([A-Z])/g, '$1_$2')
        .replace(/[-\s]/g, '_')
        .toUpperCase();
}

function writeConstantsFile() {
    const seen = new Map();
    const lines = ICONS.map(name => {
        const c = constName(name);
        if (seen.has(c)) {
            throw new Error(`Constant name collision: '${name}' and '${seen.get(c)}' both map to ${c}`);
        }
        seen.set(c, name);
        return `export const ${c} = '${name}';`;
    });
    const header = '// AUTO-GENERATED by scripts/build-icon-font.js (npm run build:icons) — do not edit.\n'
        + '// Ligature names for the Aon Symbols Outlined icon font (class "aon-symbols-outlined").\n\n';
    fs.writeFileSync(CONSTANTS_FILE, header + lines.join('\n') + '\n');
    console.log(`Wrote ${path.relative(process.cwd(), CONSTANTS_FILE)} (${lines.length} constants)`);
}

