package com.esferalia.aon.file.payroll.fan.data;

/**
 * Modalidad de pago
 */
public class MPG {
	
	private String solicitudModalidadPago;
	private String condigoCuentaCliente;
	private String tipoIdentificadorTitular;
	private String identificadorTitular;
	private String nombreTitular;
	
	public String getSolicitudModalidadPago() {
		return solicitudModalidadPago;
	}
	public void setSolicitudModalidadPago(String solicitudModalidadPago) {
		this.solicitudModalidadPago = solicitudModalidadPago;
	}
	public String getCondigoCuentaCliente() {
		return condigoCuentaCliente;
	}
	public void setCondigoCuentaCliente(String condigoCuentaCliente) {
		this.condigoCuentaCliente = condigoCuentaCliente;
	}
	public String getTipoIdentificadorTitular() {
		return tipoIdentificadorTitular;
	}
	public void setTipoIdentificadorTitular(String tipoIdentificadorTitular) {
		this.tipoIdentificadorTitular = tipoIdentificadorTitular;
	}
	public String getIdentificadorTitular() {
		return identificadorTitular;
	}
	public void setIdentificadorTitular(String identificadorTitular) {
		this.identificadorTitular = identificadorTitular;
	}
	public String getNombreTitular() {
		return nombreTitular;
	}
	public void setNombreTitular(String nombreTitular) {
		this.nombreTitular = nombreTitular;
	}
	
	
	
}
