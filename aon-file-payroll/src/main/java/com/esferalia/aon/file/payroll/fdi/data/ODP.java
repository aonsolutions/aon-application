package com.esferalia.aon.file.payroll.fdi.data;

public class ODP {
	Integer fecha;
	Integer numero;
	Integer entidadAseguradora;
	Integer fechaCambioEntidad;
	public Integer getFecha() {
		return fecha;
	}
	public void setFecha(Integer fecha) {
		this.fecha = fecha;
	}
	public Integer getNumero() {
		return numero;
	}
	public void setNumero(Integer numero) {
		this.numero = numero;
	}
	public Integer getEntidadAseguradora() {
		return entidadAseguradora;
	}
	public void setEntidadAseguradora(Integer entidadAseguradora) {
		this.entidadAseguradora = entidadAseguradora;
	}
	public Integer getFechaCambioEntidad() {
		return fechaCambioEntidad;
	}
	public void setFechaCambioEntidad(Integer fechaCambioEntidad) {
		this.fechaCambioEntidad = fechaCambioEntidad;
	}
	
	
}
