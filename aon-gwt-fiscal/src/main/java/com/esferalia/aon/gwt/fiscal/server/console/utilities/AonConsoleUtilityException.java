package com.esferalia.aon.gwt.fiscal.server.console.utilities;

public class AonConsoleUtilityException extends Exception {

    private static final long serialVersionUID = 8636530269010266596L;
    
	public AonConsoleUtilityException() {
        super();
    }
    public AonConsoleUtilityException(String message) {
        super(message);
    }
    public AonConsoleUtilityException(Throwable cause) {
        super(cause);
    }
    public AonConsoleUtilityException(String message, Throwable cause) {
        super(message, cause);
    }

}
